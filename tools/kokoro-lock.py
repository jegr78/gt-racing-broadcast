#!/usr/bin/env python3
"""Maintainer: write the hash-pinned package list of the local Kokoro voice runtime.

Run: python3 tools/kokoro-lock.py name==version [name==version ...]
List every package of the runtime, dependencies included: the runtime installs with
--no-deps. Each pin keeps the hashes of the wheels for CPython 3.12 on the supported
platforms, so one file serves every OS.
"""
import json
import re
import sys
import urllib.request
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "src/assets/driver-radio/kokoro-requirements.txt"


def usable(name):
    """A wheel CPython 3.12 can install on a supported platform."""
    if not name.endswith(".whl"):
        return False
    python, _abi, platform = name[:-4].split("-")[-3:]
    if python not in ("py3", "py2.py3", "cp312") and not (python.startswith("cp3") and "abi3" in name):
        return False
    return platform == "any" or platform.startswith(("win_amd64", "macosx", "manylinux"))


def pin(requirement):
    name, version = requirement.split("==")
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=30) as reply:
        files = json.load(reply)["urls"]
    wheels = [f for f in files if usable(f["filename"])]
    if not wheels:
        sys.exit(f"{requirement}: no usable wheel")
    print(requirement, sorted({re.split(r"-", f["filename"][:-4])[-1] for f in wheels}))
    hashes = sorted(f["digests"]["sha256"] for f in wheels)
    return f"{name}=={version} " + " ".join(f"--hash=sha256:{h}" for h in hashes)


def main():
    lines = ["# Generated by tools/kokoro-lock.py. Do not edit by hand."]
    lines += [pin(requirement) for requirement in sorted(sys.argv[1:], key=str.lower)]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
